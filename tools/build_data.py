#!/usr/bin/env python3
"""Build static/data/results.js from static/tables/metabonet_results.csv.

    python tools/build_data.py

The page reads window.MBN_RESULTS rather than fetching JSON, so it also works
when index.html is opened straight from disk (file:// blocks fetch()).

Every number on the results tables of the site comes from the CSV, which was
written by scripts/55_results_report.py from the prediction files. Nothing is
recomputed here except the four-horizon mean.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "static" / "tables" / "metabonet_results.csv"
OUT = ROOT / "static" / "data" / "results.js"
H = [30, 60, 90, 120]
METRICS = ["dtsa", "mard", "rmse", "mse"]

# Persistence on the live set, computed separately in the modelling-strategy
# analysis (2,648,723 of 2,648,987 anchors). Reference row only; it is not in
# the CSV because it was never a submission file.
PERSIST_LIVE = {30: (25.17, 13.12, 79.92), 60: (39.98, 21.31, 61.34),
                90: (49.26, 26.62, 51.81), 120: (55.48, 30.26, 46.31)}


def block(df: pd.DataFrame) -> dict:
    out = {}
    for m, g in df.groupby("model"):
        rec = {}
        for _, r in g.iterrows():
            rec[str(int(r.horizon))] = {k: round(float(r[k]), 4) for k in METRICS}
            rec[str(int(r.horizon))]["n"] = int(r.n)
        rec["mean"] = {k: round(sum(rec[str(h)][k] for h in H) / 4, 4) for k in METRICS}
        out[m] = rec
    return out


def main() -> None:
    d = pd.read_csv(CSV)
    live = block(d[d.split == "public test"])
    p = {}
    for h, (rmse, mard, dtsa) in PERSIST_LIVE.items():
        p[str(h)] = {"dtsa": dtsa, "mard": mard, "rmse": rmse,
                     "mse": round(rmse * rmse, 2), "n": 2648723}
    p["mean"] = {k: round(sum(p[str(h)][k] for h in H) / 4, 4) for k in METRICS}
    live["persistence"] = p

    loso = {}
    for f, g in d[d.split == "held-out study"].groupby("fold"):
        loso[f] = block(g)

    # Patient-atlas catalogue: every figure file under static/atlas, parsed from
    # its name  <kind>__<split>__<level>.html
    atlas = []
    for f in sorted((ROOT / "static" / "atlas").glob("*.html")):
        parts = f.stem.split("__")
        if f.name == "index.html" or len(parts) < 3:
            continue
        if parts[0] == "atlas":
            kind, split, level = parts[1], parts[2], "__".join(parts[3:])
        elif parts[0] == "pump":
            kind, split, level = "pumpprofile", parts[1], "__".join(parts[2:])
        elif parts[0] == "multiday":
            kind, split, level = "multiday", parts[1], parts[2]
        else:
            continue
        atlas.append({"kind": kind, "split": split,
                      "level": level.replace("_", " "), "file": f.name})

    payload = {"live": live, "loso": loso, "atlas": atlas,
               "source": "static/tables/metabonet_results.csv"}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("/* generated by tools/build_data.py - do not edit by hand */\n"
                   "window.MBN_RESULTS = " + json.dumps(payload, separators=(",", ":")) + ";\n")
    print(f"wrote {OUT}  live models {len(live)}  folds {sorted(loso)}  atlas figures {len(atlas)}")


if __name__ == "__main__":
    main()
